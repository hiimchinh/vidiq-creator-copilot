/**
 * The two claim checks side by side, computed from the same answer and the same tool results:
 * the exact-text baseline (how AI Coach behaved on 4 Nov 2026) and provenance binding (this repo).
 */
import { stripMarkdown } from "./markdown-text";
import { exactLabelFor, naiveFlags } from "./naive-exact-checker";
import type { Source } from "./provenance";
import { displayText, verifyAnswer } from "./verify-answer";

export interface ExactFlag {
  label?: string;
  display: string;
  score: boolean;
}

export interface ClaimChecks {
  exact: { flags: ExactFlag[]; note: string };
  provenance: { verified: number; total: number; note: string };
}

const plural = (n: number, word: string) => `${n} ${word}${n === 1 ? "" : "s"}`;

function exactNote(flags: ExactFlag[], scoreClaims: number): string {
  if (flags.length === 0) return "The exact-text check flags nothing in this answer.";
  const item = (f: ExactFlag) => {
    const value = f.score ? `${f.display}/100` : f.display;
    return f.label ? `“${f.label}” (${value})` : value;
  };
  const list = flags.map(item).join(", ");
  if (flags.every((f) => f.score)) {
    const others = scoreClaims > flags.length ? " Other title scores are unchanged." : "";
    return `Heads up: these claimed scores were not generated by a title-scoring run for the exact title text shown: ${list}; treat them as unverified.${others}`;
  }
  return `Heads up: these claimed figures were not found in a tool result for the exact text shown: ${list}; treat them as unverified.`;
}

function provenanceNote(verified: number, total: number, allScores: boolean): string {
  const noun = allScores ? "score" : "figure";
  const hint = `Hover or focus a ${noun} to see its source.`;
  if (total === 0) return "This answer states no figures to check.";
  if (verified < total) {
    return `${verified} of ${total} figures match their vidIQ tool results; ${total - verified} flagged as unverified. ${hint}`;
  }
  if (total === 1) return `The 1 ${noun} matches the vidIQ call that produced it. ${hint}`;
  return `All ${plural(total, noun)} match the vidIQ calls that produced them. ${hint}`;
}

export function compareClaimChecks(answer: string, sources: Source[]): ClaimChecks {
  const { segments, summary } = verifyAnswer(answer, sources);
  const shown = displayText(segments);
  const spans = shown.claims.map((c) => ({ start: c.start, end: c.end, text: c.claim.display }));
  const flagged = naiveFlags(shown.text, spans, sources);
  const isScore = (i: number) => shown.claims[i]?.claim.field === "score";
  const flags = spans.flatMap((span, i): ExactFlag[] => {
    if (!flagged[i]) return [];
    const label = exactLabelFor(shown.text, span);
    return [{ ...(label === undefined ? {} : { label: stripMarkdown(label).trim() }), display: span.text, score: isScore(i) }];
  });
  const scoreClaims = spans.filter((_, i) => isScore(i)).length;
  const total = summary.verified + summary.flagged;
  return {
    exact: { flags, note: exactNote(flags, scoreClaims) },
    provenance: { verified: summary.verified, total, note: provenanceNote(summary.verified, total, total > 0 && scoreClaims === total) },
  };
}
