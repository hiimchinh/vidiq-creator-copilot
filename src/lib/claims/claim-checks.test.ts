import { describe, expect, it } from "vitest";
import titleEspresso from "../../fixtures/replay/title-espresso.json";
import type { ReplayScenario } from "../replay/replay-types";
import { scenarioSteps } from "../replay/scenario-steps";
import { compareClaimChecks } from "./claim-checks";
import { buildSources } from "./provenance";
import { ESPRESSO_SOURCES } from "./test-sources";

const scenario = titleEspresso as unknown as ReplayScenario;
const answer = scenario.answer.chunks.map((c) => c.text).join("");
const espresso = compareClaimChecks(answer, buildSources(scenarioSteps(scenario)));

describe("compareClaimChecks on the recorded espresso answer (vidIQ results: 99, then 97, 96, 96)", () => {
  it("exact-text check raises AI Coach's false alarm on the creator's own 99, because the row says (yours)", () => {
    expect(espresso.exact.flags).toEqual([{ label: "I Tried 5 Cheap Espresso Machines So You Don't Have To (yours)", display: "99", score: true }]);
    // Wording pattern copied from the AI Coach screenshot of 4 Nov 2026.
    expect(espresso.exact.note).toBe(
      "Heads up: these claimed scores were not generated by a title-scoring run for the exact title text shown: " +
        "“I Tried 5 Cheap Espresso Machines So You Don't Have To (yours)” (99/100); treat them as unverified. " +
        "Other title scores are unchanged.",
    );
  });

  it("provenance check binds all 8 scores to the call that produced them and flags none", () => {
    expect(espresso.provenance).toEqual({
      verified: 8,
      total: 8,
      note: "All 8 scores match the vidIQ calls that produced them. Hover or focus a score to see its source.",
    });
  });
});

describe("compareClaimChecks on other answers", () => {
  it("names unlabelled figures that are not in the tool data, and counts what provenance flags", () => {
    const checks = compareClaimChecks("home barista gets 50,000 searches.", ESPRESSO_SOURCES);
    expect(checks.exact.note).toBe("Heads up: these claimed figures were not found in a tool result for the exact text shown: 50,000; treat them as unverified.");
    expect(checks.provenance).toEqual({
      verified: 0,
      total: 1,
      note: "0 of 1 figures match their vidIQ tool results; 1 flagged as unverified. Hover or focus a figure to see its source.",
    });
  });

  it("says so when the exact-text check flags nothing", () => {
    const checks = compareClaimChecks("Your title scores [[c1.score=99]].", ESPRESSO_SOURCES);
    expect(checks.exact).toEqual({ flags: [], note: "The exact-text check flags nothing in this answer." });
    expect(checks.provenance.note).toBe("The 1 score matches the vidIQ call that produced it. Hover or focus a score to see its source.");
  });
});
